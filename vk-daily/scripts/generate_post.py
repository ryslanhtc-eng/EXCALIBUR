"""Build one ~2000-char Ufa story post + 4–8 word cover headline."""
from __future__ import annotations

import hashlib
import json
from datetime import date
from pathlib import Path
from typing import Any

from validate_post import validate_headline, validate_post, load_banned, load_tenant


def _load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def pick_news(items: list[dict], today: date) -> dict:
    dated = []
    for item in items:
        try:
            d = date.fromisoformat(str(item["date"]))
        except (KeyError, ValueError):
            continue
        if d <= today:
            dated.append((d, item))
    if not dated:
        raise RuntimeError("news-bank has no item on or before today")
    dated.sort(key=lambda pair: pair[0], reverse=True)
    return dated[0][1]


def pick_composition(compositions: list[dict], seed: str, used: list[str]) -> dict:
    unused = [c for c in compositions if c.get("id") not in used]
    pool = unused if unused else [c for c in compositions if not used or c.get("id") != used[-1]] or compositions
    digest = hashlib.sha256(seed.encode("utf-8")).hexdigest()
    idx = int(digest, 16) % len(pool)
    return pool[idx]


def pick_pose_wardrobe(pose_refs: list[dict], seed: str, used: list[str]) -> dict:
    unused = [p for p in pose_refs if p.get("id") not in used]
    pool = unused if unused else [p for p in pose_refs if not used or p.get("id") != used[-1]] or pose_refs
    digest = hashlib.sha256((seed + "|pose").encode("utf-8")).hexdigest()
    idx = int(digest, 16) % len(pool)
    return pool[idx]



def _headlines_for(news: dict) -> list[str]:
    angle = news.get("angle") or ""
    if angle == "price_pulse":
        return [
            "Уфа снова в тройке",
            "Квадрат уже почти двести",
            "Август поднял уфимский ценник",
            "Первичка растёт без суеты",
        ]
    if angle == "avg_ticket":
        return [
            "Средняя новостройка восемь два",
            "Билет в новостройку вырос",
            "Уфимская квартира снова дороже",
        ]
    if angle == "zadatok_trap":
        return [
            "Как не потерять задаток при покупке",
            "Задаток до проверки документов опасен",
            "Ошибки задатка при покупке жилья",
            "Как не потерять задаток в Уфе",
        ]
    if angle == "mortgage_window":
        return [
            "Платёж считают до октября",
            "Семейная не ждёт чуда",
            "Окно по семейной уже узкое",
        ]
    return ["Уфа считает квартирный шаг", "Честный разбор без суеты"]


def pick_headline(news: dict, seed: str, tenant: dict) -> str:
    options = _headlines_for(news)
    digest = hashlib.sha256((seed + "|headline").encode("utf-8")).hexdigest()
    ordered = [options[int(digest, 16) % len(options)]] + options
    for candidate in ordered:
        if not validate_headline(candidate, tenant):
            return candidate
    raise RuntimeError("no valid cover headline")


def _price_pulse_body(news: dict) -> str:
    numbers = news.get("numbers") or {}
    sqm = numbers.get("sqm_rub")
    mom = numbers.get("mom_pct")
    sqm_txt = f"{sqm / 1000:.1f}".replace(".0", "") if isinstance(sqm, (int, float)) else "почти 198"
    if isinstance(sqm, (int, float)):
        sqm_txt = f"{sqm / 1000:.1f}".replace(".", ",")
    mom_txt = f"{mom}".replace(".", ",") if mom is not None else "1,6"
    return f"""Уфа снова в тройке по росту цен на новостройки среди городов-миллионников. Не "вся страна", не столичный шум - конкретно наша первичка.

РБК Недвижимость по августу: квадрат на первичном рынке в столице Башкирии вырос на {mom_txt}% и дошёл до {sqm_txt} тыс. рублей. Впереди только Москва и Красноярск. Это не взрыв, это уже привычная уфимская инерция: лето заканчивается, люди возвращаются из отпусков, застройщики чуть подтягивают ценник.

Что из этого следует, если вы смотрите квартиру в Сипайлово, Дёме или на вторичке рядом.

Первое. Цифра "за квадрат" - средняя по городу. В одном доме 190, в соседнем 230, в черновой студии и в отделке с мебелью - разные вселенные. Сравнивайте не заголовок объявления, а конкретный лот: этаж, кухня, двор, год, сколько уже висит.

Второе. Сравнивайте реальную транспортную доступность и инфраструктуру. Маршруты простые: автобус, трамвай, электричка, машина и пробки на выезде. Реальное время в пути до школы и работы решает куда больше, чем любые рекламные фразы. 😅

Третье. Пока в республике большой навес непроданных квартир, застройщикам незачем прыгать на 3-4% в месяц. Спокойный шаг 0,3-0,5% реалистичнее паники "завтра убежит". Паника обычно дороже, чем вечер с калькулятором.

Если жильё нужно под семейную программу - пересчитайте платёж до осени. Условия уже сужали, и октябрь не про погоду, а про то, что часть семей просто не пройдёт в ту же корзину.

Я Руслан Мухтаров, Самолет Плюс, Уфа. Офис в Сипайлово на Жукова 39/1 оф.303, сделки по всей Уфе. Спокойно пройдёмся по вашему объекту: платёж, риски, торг, документы.

Напишите в сообщения сообщества - разберём ваш вариант по цифрам, без воды."""


def _avg_ticket_body(news: dict) -> str:
    numbers = news.get("numbers") or {}
    apt = numbers.get("apartment_mln", 8.2)
    mom = numbers.get("mom_pct", 1.3)
    apt_txt = str(apt).replace(".", ",")
    mom_txt = str(mom).replace(".", ",")
    return f"""Средняя новая квартира в Уфе по итогам августа - почти {apt_txt} млн рублей. Плюс {mom_txt}% к июлю. Это не "ваш конкретный дом", это средняя температура по больнице - но направление такое.

Башинформ сослался на "Мир квартир". Я эту цифру не раздуваю и не делю на красивые студии в рекламе. Если вам приносят лот за 6,2 и лот за 11, оба могут быть "рынком". Средняя нужна, чтобы не верить заголовку "последняя квартира по старой цене" без таблицы.

В Дёме, Сипайлово, Инорсе смотрите связку: платёж, срок ключей, что уже сдано во дворе, кто сосед по подъезду. Новостройка без отделки и вторичка с ремонтом 2012 года считаются в разных тетрадях. Смешивать их в одной фразе "надо брать, пока не улетело" - плохая привычка.

Ещё раз про транспорт. Честный уфимский маршрут - автобус, трамвай, электричка, машина и выездные пробки. Если вам обещают сказочную инфраструктуру через год - всегда перепроверяйте генплан и реальные стройки.

Я не тороплю "закрыть сегодня". Я предлагаю закрыть самообман: сравнить три лота на бумаге, прикинуть платёж, посмотреть дом днём, не в золотом закате с дрона. Офис в Сипайлово на Жукова 39/1 оф.303, сделки по всей Уфе.

Руслан Мухтаров, Самолет Плюс. Напишите в сообщения сообщества, если нужен разбор вашего варианта без воды и спешки."""


def _mortgage_body(_news: dict) -> str:
    return """Семейная ипотека к 1 октября снова в центре внимания, но вокруг много лишнего шума. Минфин подтвердил главное: условия семейной ипотеки меняются не раньше 1 октября 2026 года, а до этой даты вся программа действует строго в текущем виде. Никаких внезапных закрытий со дня на день не планируется.

Но это не повод расслабляться или ждать мифических "лучших времён". Если ваша семья подходит под действующие правила, разумнее сверить критерии и документы прямо сейчас, а не 30 сентября в спешке.

Что важно понимать уфимским семьям без иллюзий.

Первое. Условия до 1 октября стабильны, но банки смотрят каждого заёмщика предельно внимательно. Я не называю конкретные процентные ставки без договора перед глазами: у каждого банка своя сетка, свои надбавки и требования к первому взносу. Обещать гарантированное одобрение - обман чистой воды. Решение принимает кредитный комитет банка после скоринга, проверки занятости, кредитной нагрузки и документов созаёмщиков.

Второе. Не путайте семейную ипотеку с ипотечными каникулами по закону ФЗ-229. Каникулы - это временная отсрочка выплат при падении дохода или форс-мажоре. А семейная ипотека - это государственная льготная программа на покупку конкретного жилья для семей с детьми. Это совершенно разные вещи и разные статьи закона.

Что стоит проверить семье до 1 октября:
1. Подходит ли состав семьи и возраст детей под действующие требования программы.
2. Проходит ли официальный подтверждённый доход с учётом всех текущих кредитов.
3. Готов ли первоначальный взнос и сертификат на материнский капитал.
4. Выбраны ли реальные объекты в Уфе для сравнения параметров, а не абстрактные картинки.

Практика показывает: спокойный расчёт семейного бюджета заранее сохраняет и нервы, и деньги. Когда на руках есть одобренное решение банка и проверенные документы, можно уверенно выбирать квартиру в Сипайлово, Дёме, Зелёной роще или центре, понимая точную сумму ежемесячного платежа.

Я Руслан Мухтаров, Самолет Плюс. Офис в Сипайлово на Жукова 39/1 оф.303, сделки по всей Уфе. Мы не обещаем чудес и работаем строго по фактам.

Напишите в сообщения сообщества - сверим вашу ситуацию и спокойно посчитаем платёж по документам."""


def _zadatok_trap_body(_news: dict) -> str:
    return """Самая частая ошибка покупателя жилья: влюбиться в планировку, испугаться, что лот уведут, и перевести задаток прямо на кухне при первом осмотре.

Сценарий для уфимского рынка классический. Смотрит человек свежую двушку в Сипайлово на Жукова или вторичку в Зелёной роще. Цена чуть приятнее соседних домов, ремонт аккуратный, собственник доброжелательно улыбается: «Мне с утра уже трое звонили, готовы забрать сегодня. Переведите тысяч пятьдесят задатка, я прямо сейчас сниму объявление». Рука сама тянется к банковскому приложению. 😅

Вот здесь и захлопывается финансовая ловушка.

Между словами «мне понравилась квартира» и любым переводом средств обязана стоять дотошная проверка документов. Не беглый взгляд на паспорт продавца, а разбор истории объекта до винтика.

Почему эти деньги потом так тяжело вернуть?

Во-первых, люди путают задаток и аванс. По закону задаток обеспечивает исполнение обязательств. Если сделка срывается по вашей вине (например, банк отказал в ипотеке на этот конкретный дом или вы просто передумали), продавец оставляет всю сумму себе абсолютно законно.

Во-вторых, перевод на карту по номеру телефона без грамотного письменного договора это вообще не задаток. В суде это часто превращается в неосновательное обогащение, по которому взыскать средства с закредитованного гражданина можно лишь на бумаге.

В-третьих, если отдать деньги до проверки документов, можно внезапно узнать неприятные вещи: квартира куплена на маткапитал без выделения детских долей, у собственника висят долги у приставов, продавец скрыл супруга или жилье получено по свежему наследству с тайными родственниками.

Чеклист: что сделать ДО перевода денег:

1. Заказать свежую выписку из ЕГРН и лично сверить данные собственника по паспорту.
2. Проверить человека по базам судебных приставов и реестру банкротств.
3. Оформить передачу средств только письменным соглашением с четким условием: если банк бракует объект или всплывают скрытые обременения, вся сумма возвращается покупателю без штрафов.

Я Руслан Мухтаров, Самолет Плюс, Уфа. Наш офис в Сипайлово: ул. Жукова 39/1, офис 303. Если присмотрели квартиру и продавец торопит с задатком, не спешите.

Напишите в сообщения сообщества, проверим документы и объект спокойно, без суеты и без риска."""


def _fit_length(text: str, min_c: int, max_c: int) -> str:
    body = text.strip()
    filler = (
        "\n\nЕщё одна бытовая проверка перед показом: посмотрите дом в обычный будний час, "
        "не в воскресенье. Двор, парковка, шум с дороги, магазин пешком. В Уфе это решает "
        "больше, чем красивое слово в шапке объявления."
    )
    while len(body) < min_c:
        body = (body + filler).strip()
        if len(body) > max_c:
            break
    if len(body) > max_c:
        body = body[: max_c - 1].rsplit(" ", 1)[0]
    return body.strip()


def render_post(news: dict, tenant: dict) -> str:
    angle = news.get("angle")
    if angle == "zadatok_trap":
        raw = _zadatok_trap_body(news)
    elif angle == "avg_ticket":
        raw = _avg_ticket_body(news)
    elif angle == "mortgage_window":
        raw = _mortgage_body(news)
    else:
        raw = _price_pulse_body(news)
    spec = tenant["post"]
    return _fit_length(raw, int(spec["min_chars"]), int(spec["max_chars"]))


def generate(
    vk_root: Path,
    today: date,
    seed: str,
    used_compositions: list[str],
    used_pose_refs: list[str] | None = None,
) -> dict[str, Any]:
    tenant = load_tenant(vk_root)
    banned = load_banned(vk_root)
    news_bank = _load_json(vk_root / "data" / "news-bank.json")
    compositions = _load_json(vk_root / "data" / "compositions.json")["compositions"]
    pose_file = vk_root / "data" / "pose_wardrobe.json"
    pose_catalog: list[dict] = _load_json(pose_file).get("pose_wardrobe", []) if pose_file.is_file() else []
    news = pick_news(news_bank["items"], today)
    composition = pick_composition(compositions, seed, used_compositions)
    pose_ref = pick_pose_wardrobe(pose_catalog, seed, used_pose_refs or []) if pose_catalog else {}
    headline = pick_headline(news, seed, tenant)
    post = render_post(news, tenant)

    errors = validate_post(post, tenant, banned)
    errors.extend(validate_headline(headline, tenant))
    if errors:
        raise RuntimeError("post validation failed: " + "; ".join(errors))

    return {
        "post": post,
        "headline": headline,
        "dek": "Ошибки аванса и задатка: что проверить до перевода денег",
        "news": news,
        "composition": composition,
        "pose_wardrobe": pose_ref,
        "char_count": len(post),
    }

